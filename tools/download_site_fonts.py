"""Downloads the two Google Fonts that only the website uses (Anton, Playfair Display italic).

The rest of the site's fonts come from design/fonts/. The .woff2 files are committed, so
this is only needed to update them:

    python3 tools/download_site_fonts.py
"""
import re
import urllib.request
from pathlib import Path

TARGET = Path(__file__).resolve().parent.parent / "site" / "fonts"
FAMILIES = [
    ("Anton", None, "ofl/anton"),
    ("Playfair Display", "ital,wght@1,700;1,900", "ofl/playfairdisplay"),
]
BROWSER = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"


def download(url):
    req = urllib.request.Request(url, headers={"User-Agent": BROWSER})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def main():
    TARGET.mkdir(parents=True, exist_ok=True)
    rules = ["/* Fonts used only by the website. Generated by tools/download_site_fonts.py */"]
    for family, axes, repo in FAMILIES:
        q = family.replace(" ", "+") + (":" + axes if axes else "")
        css = download(f"https://fonts.googleapis.com/css2?family={q}&display=swap").decode()
        for subset, body in re.findall(r"/\* ([a-z-]+) \*/\s*@font-face\s*\{(.*?)\}", css, re.S):
            if subset not in {"latin", "latin-ext"}:
                continue
            style = re.search(r"font-style:\s*(\w+)", body).group(1)
            weight = re.search(r"font-weight:\s*([\d ]+);", body).group(1).strip().split()[0]
            url = re.search(r"url\((https://[^)]+)\)", body).group(1)
            unicode_range = re.search(r"unicode-range:\s*([^;]+);", body).group(1)
            file = f"{family.lower().replace(' ', '-')}-{weight}{'-italic' if style == 'italic' else ''}-{subset}.woff2"
            (TARGET / file).write_bytes(download(url))
            rules.append(
                "@font-face{font-family:'%s';font-style:%s;font-weight:%s;font-display:swap;"
                "src:url(%s) format('woff2');unicode-range:%s}" % (family, style, weight, file, unicode_range)
            )
        print("ok", family)
    (TARGET / "site-fonts.css").write_text("\n".join(rules) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
