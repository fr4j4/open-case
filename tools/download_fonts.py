"""Downloads the Google Fonts that Open Case uses and puts them in design/fonts/.

Only needed when a family is added or the existing ones need updating: the repo ships the
.woff2 files and their licenses, so the exporter works offline.

    python3 tools/download_fonts.py
"""
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "design" / "fonts"

FAMILIES = [
    ("Barlow Condensed", "wght@500;600;700", "ofl/barlowcondensed"),
    ("Public Sans", "ital,wght@0,400;0,600;0,800;1,400", "ofl/publicsans"),
    ("IBM Plex Mono", "wght@400;600", "ofl/ibmplexmono"),
    ("Special Elite", None, "apache/specialelite"),
    ("Courier Prime", "wght@400;700", "ofl/courierprime"),
    ("Caveat", "wght@500;700", "ofl/caveat"),
    ("Nothing You Could Do", None, "ofl/nothingyoucoulddo"),
    ("Permanent Marker", None, "apache/permanentmarker"),
    ("Homemade Apple", None, "apache/homemadeapple"),
    ("Dancing Script", "wght@500", "ofl/dancingscript"),
    ("Playfair Display", "wght@700;900", "ofl/playfairdisplay"),
    ("Libre Baskerville", "ital,wght@0,400;0,700;1,400", "ofl/librebaskerville"),
    ("Roboto", "wght@400;500;700", "ofl/roboto"),
]
# Only the alphabets a case in Spanish or English needs, plus arrows and symbols.
SUBSETS = {"latin", "latin-ext", "symbols", "math"}
BROWSER = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"


def download(url):
    req = urllib.request.Request(url, headers={"User-Agent": BROWSER})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def slug(name):
    return name.lower().replace(" ", "-")


def main():
    TARGET.mkdir(parents=True, exist_ok=True)
    rules = ["/* Open Case fonts, served from the repo. Generated by tools/download_fonts.py */"]
    for family, axes, repo in FAMILIES:
        q = family.replace(" ", "+") + (":" + axes if axes else "")
        css = download(f"https://fonts.googleapis.com/css2?family={q}&display=swap").decode()
        for subset, body in re.findall(r"/\* ([a-z-]+) \*/\s*@font-face\s*\{(.*?)\}", css, re.S):
            if subset not in SUBSETS:
                continue
            style = re.search(r"font-style:\s*(\w+)", body).group(1)
            weight = re.search(r"font-weight:\s*(\d+)", body).group(1)
            url = re.search(r"url\((https://[^)]+)\)", body).group(1)
            unicode_range = re.search(r"unicode-range:\s*([^;]+);", body).group(1)
            file = f"{slug(family)}-{weight}{'-italic' if style == 'italic' else ''}-{subset}.woff2"
            (TARGET / file).write_bytes(download(url))
            rules.append(
                "@font-face{font-family:'%s';font-style:%s;font-weight:%s;font-display:block;"
                "src:url(%s) format('woff2');unicode-range:%s}" % (family, style, weight, file, unicode_range)
            )
        folder = TARGET / "licenses"
        folder.mkdir(exist_ok=True)
        license_name = "OFL.txt" if repo.startswith("ofl/") else "LICENSE.txt"
        text = download(f"https://raw.githubusercontent.com/google/fonts/main/{repo}/{license_name}")
        (folder / f"{slug(family)}-{license_name}").write_bytes(text)
        print("ok", family)
    (TARGET / "fonts.css").write_text("\n".join(rules) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
